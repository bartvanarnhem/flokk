@Composable
fun ConnectionFormScreen(
    profileId: String?,
    onSaved: () -> Unit,
    onCancel: () -> Unit,
) {
    val app = LocalFlokk.current
    val scope = rememberCoroutineScope()
    val snackbarHostState = remember { SnackbarHostState() }

    val existing = remember { profileId?.let { app.profileStore.getProfile(it) } }
    val otherProfiles = remember { app.profileStore.listProfiles().filterNot { it.id == existing?.id } }

    var name by remember { mutableStateOf(existing?.name.orEmpty()) }
    var host by remember { mutableStateOf(existing?.host.orEmpty()) }
    var port by remember { mutableStateOf((existing?.port ?: 22).toString()) }
    var username by remember { mutableStateOf(existing?.username.orEmpty()) }
    var herdrSession by remember { mutableStateOf(existing?.herdrSession.orEmpty()) }
    var herdrBinary by remember { mutableStateOf(existing?.herdrBinary ?: "herdr") }
    var jumpHostId by remember { mutableStateOf(existing?.jumpHostId) }

    var useKeyAuth by remember { mutableStateOf(existing?.let { it.auth is AuthMethod.PrivateKey } ?: true) }
    var keyMode by remember { mutableStateOf(KeyMode.EXISTING) }
    var password by remember { mutableStateOf((existing?.auth as? AuthMethod.Password)?.password.orEmpty()) }
    var privateKey by remember { mutableStateOf((existing?.auth as? AuthMethod.PrivateKey)?.pem.orEmpty()) }
    var passphrase by remember { mutableStateOf((existing?.auth as? AuthMethod.PrivateKey)?.passphrase.orEmpty()) }
    var passwordVisible by remember { mutableStateOf(false) }
    var protectWithPassphrase by remember { mutableStateOf(false) }
    var keyName by remember { mutableStateOf("flokk_${name.ifBlank { "key" }}") }
    var generated by remember { mutableStateOf<GeneratedSshKey?>(null) }

    var installDialogOpen by remember { mutableStateOf(false) }
    var installPassword by remember { mutableStateOf("") }
    var installing by remember { mutableStateOf(false) }

    var confirmDelete by remember { mutableStateOf(false) }
    var jumpMenuOpen by remember { mutableStateOf(false) }
    var autoConnect by remember { mutableStateOf(existing?.autoConnect ?: false) }

    val canSave = host.isNotBlank() && username.isNotBlank() &&
        (if (useKeyAuth) privateKey.isNotBlank() else password.isNotBlank())

    fun save() {
        val profile = ConnectionProfile(
            id = existing?.id ?: UUID.randomUUID().toString(),
            name = name.trim(),
            host = host.trim(),
            port = port.toIntOrNull() ?: 22,
            username = username.trim(),
            auth = if (useKeyAuth) {
                AuthMethod.PrivateKey(privateKey, passphrase.takeIf { it.isNotBlank() })
            } else {
                AuthMethod.Password(password)
            },
            herdrSession = herdrSession.trim().takeIf { it.isNotBlank() },
            herdrBinary = herdrBinary.trim().takeIf { it.isNotBlank() } ?: "herdr",
            jumpHostId = jumpHostId,
            lastConnectedAt = existing?.lastConnectedAt,
            autoConnect = autoConnect,
        )
        app.profileStore.saveProfile(profile)
        onSaved()
    }

    Column(modifier = Modifier.fillMaxSize().background(Tui.background)) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 12.dp, vertical = 10.dp),
            horizontalArrangement = Arrangement.spacedBy(10.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            TuiIconButton(icon = Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back to connections", onClick = onCancel)
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = if (existing == null) "add connection" else "edit connection",
                    style = Tui.body,
                )
                if (host.isNotBlank() || username.isNotBlank() || name.isNotBlank()) {
                    Text(
                        text = listOfNotNull(
                            name.trim().takeIf { it.isNotBlank() },
                            "$username@${host.ifBlank { "…" }}:$port",
                        ).joinToString(" · "),
                        style = Tui.label.copy(color = Tui.textFaint),
                    )
                }
            }
        }

        Column(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 16.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp),
        ) {
            TuiTextField(
                value = name,
                onValueChange = { name = it },
                label = "name",
                placeholder = "e.g. home server",
            )

            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                TuiTextField(
                    value = host,
                    onValueChange = { host = it },
                    label = "host",
                    placeholder = "example.com or 10.0.0.5",
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Uri),
                    modifier = Modifier.weight(2f),
                )
                TuiTextField(
                    value = port,
                    onValueChange = { port = it.filter(Char::isDigit) },
                    label = "port",
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                    modifier = Modifier.weight(1f),
                )
            }
            TuiTextField(
                value = username,
                onValueChange = { username = it },
                label = "username",
                placeholder = "e.g. bart",
            )

            Column {
                Text(text = "auth", style = Tui.label, modifier = Modifier.padding(bottom = 4.dp))
                TuiSegmentedRow(
                    options = listOf("key", "password"),
                    selectedIndex = if (useKeyAuth) 0 else 1,
                    onSelect = { useKeyAuth = it == 0 },
                )
            }

            if (useKeyAuth) {
                KeyAuthSection(
                    keyMode = keyMode,
                    onKeyMode = { keyMode = it },
                    privateKey = privateKey,
                    onPrivateKey = { privateKey = it },
                    passphrase = passphrase,
                    onPassphrase = { passphrase = it },
                    keyName = keyName,
                    onKeyName = { keyName = it },
                    protectWithPassphrase = protectWithPassphrase,
                    onProtectWithPassphrase = { protectWithPassphrase = it },
                    generated = generated,
                    onGenerated = { generated = it },
                    canInstall = host.isNotBlank() && username.isNotBlank(),
                    onInstall = { installDialogOpen = true },
                )
            } else {
                TuiTextField(
                    value = password,
                    onValueChange = { password = it },
                    label = "password",
                    visualTransformation = if (passwordVisible) VisualTransformation.None else PasswordVisualTransformation(),
                    keyboardOptions = KeyboardOptions(imeAction = ImeAction.Done),
                    trailing = {
                        IconButton(onClick = { passwordVisible = !passwordVisible }, modifier = Modifier.size(20.dp)) {
                            Icon(
                                if (passwordVisible) Icons.Filled.VisibilityOff else Icons.Filled.Visibility,
                                contentDescription = if (passwordVisible) "Hide password" else "Show password",
                                tint = Tui.textFaint,
                            )
                        }
                    },
                )
            }

            TuiCheckbox(
                checked = autoConnect,
                onCheckedChange = { autoConnect = it },
                label = "autoconnect on start",
            )

            TuiExpandableSection(title = "advanced") {
                Column {
                    Text(text = "jump host", style = Tui.label, modifier = Modifier.padding(bottom = 4.dp))
                    Box {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(Tui.inputBackground, RoundedCornerShape(5.dp))
                                .clickable(
                                    interactionSource = remember { MutableInteractionSource() },
                                    indication = null,
                                    enabled = otherProfiles.isNotEmpty(),
                                    onClick = { jumpMenuOpen = true },
                                )
                                .padding(horizontal = 10.dp, vertical = 10.dp),
                            horizontalArrangement = Arrangement.SpaceBetween,
                        ) {
                            val label = jumpHostId?.let { id -> otherProfiles.firstOrNull { it.id == id }?.displayName }
                                ?: if (otherProfiles.isEmpty()) "no other saved hosts" else "none (direct connection)"
                            Text(text = label, style = Tui.body.copy(color = if (jumpHostId != null) Tui.text else Tui.textFaint))
                            Text(text = "▾", style = Tui.label)
                        }
                        DropdownMenu(expanded = jumpMenuOpen, onDismissRequest = { jumpMenuOpen = false }) {
                            DropdownMenuItem(
                                text = { Text("none (direct connection)") },
                                onClick = { jumpHostId = null; jumpMenuOpen = false },
                            )
                            otherProfiles.forEach { p ->
                                DropdownMenuItem(
                                    text = { Text(p.displayName) },
                                    onClick = { jumpHostId = p.id; jumpMenuOpen = false },
                                )
                            }
                        }
                    }
                }

                Column {
                    Text(text = "herdr", style = Tui.label, modifier = Modifier.padding(bottom = 4.dp))
                    Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                        TuiTextField(
                            value = herdrSession,
                            onValueChange = { herdrSession = it },
                            label = "session",
                            placeholder = "default (blank = HERDR_SESSION unset)",
                        )
                        TuiTextField(
                            value = herdrBinary,
                            onValueChange = { herdrBinary = it },
                            label = "binary",
                            placeholder = "herdr",
                        )
                    }
                }
            }

            if (existing != null) {
                TuiOutlineButton(
                    text = "delete connection",
                    contentColor = Tui.accentRed,
                    onClick = { confirmDelete = true },
                )
            }

            Spacer(modifier = Modifier.size(4.dp))
        }

        Row(
            modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 12.dp),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            TuiButton(text = "save connection", enabled = canSave, modifier = Modifier.weight(2f), onClick = ::save)
            TuiOutlineButton(text = "cancel", modifier = Modifier.weight(1f), onClick = onCancel)
        }

        SnackbarHost(snackbarHostState) { Snackbar(it) }
    }

    if (installDialogOpen) {
        AlertDialog(
            onDismissRequest = { if (!installing) installDialogOpen = false },
            title = { Text("Install key on $username@$host") },
            text = {
                Column {
                    Text("One-time password for $username@$host — used only for this install, never saved.")
                    Spacer(modifier = Modifier.size(8.dp))
                    OutlinedTextField(
                        value = installPassword,
                        onValueChange = { installPassword = it },
                        singleLine = true,
                        visualTransformation = PasswordVisualTransformation(),
                        enabled = !installing,
                    )
                }
            },
            confirmButton = {
                TextButton(
                    enabled = installPassword.isNotBlank() && !installing,
                    onClick = {
                        val pubKey = generated?.publicKeyLine ?: return@TextButton
                        installing = true
                        scope.launch {
                            val result = SshTransport.installPublicKey(
                                host = host.trim(),
                                port = port.toIntOrNull() ?: 22,
                                username = username.trim(),
                                password = installPassword,
                                publicKeyLine = pubKey,
                                hostKeyVerifier = app.hostKeyVerifier,
                            )
                            installing = false
                            installDialogOpen = false
                            installPassword = ""
                            snackbarHostState.showSnackbar(
                                result.fold(
                                    onSuccess = { "Installed — key appended to authorized_keys." },
                                    onFailure = { "Install failed: ${it.message ?: it.javaClass.simpleName}" },
                                ),
                            )
                        }
                    },
                ) { Text(if (installing) "installing…" else "install") }
            },
            dismissButton = {
                TextButton(enabled = !installing, onClick = { installDialogOpen = false; installPassword = "" }) {
                    Text("Cancel")
                }
            },
        )
    }

    if (confirmDelete && existing != null) {
        TuiConfirmDialog(
            title = "Delete connection?",
            text = "“${existing.displayName}” will be removed from this device.",
            confirmLabel = "Delete",
            onConfirm = {
                app.profileStore.deleteProfile(existing.id)
                confirmDelete = false
                onSaved()
            },
            onDismiss = { confirmDelete = false },
        )
    }
}
