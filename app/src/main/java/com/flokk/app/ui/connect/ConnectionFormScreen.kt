@Composable
fun ConnectionFormScreen(
    profileId: String?,
    onSaved: () -> Unit,
    onCancel: () -> Unit,
) {
    val app = LocalFlokk.current
    val scope = rememberCoroutineScope()

    val existing = remember { profileId?.let { app.profileStore.getProfile(it) } }
    val otherProfiles = remember { app.profileStore.listProfiles().filterNot { it.id == existing?.id } }

    var name by remember { mutableStateOf(existing?.name.orEmpty()) }
    var host by remember { mutableStateOf(existing?.host.orEmpty()) }
    var port by remember { mutableStateOf((existing?.port ?: 22).toString()) }
    var username by remember { mutableStateOf(existing?.username.orEmpty()) }
    var herdrSession by remember { mutableStateOf(existing?.herdrSession.orEmpty()) }
    var herdrBinary by remember { mutableStateOf(existing?.herdrBinary ?: "herdr") }
    var jumpHostId by remember { mutableStateOf(existing?.jumpHostId) }

    var useKeyAuth by remember { mutableStateOf(existing?.let { it.auth is AuthMethod.PrivateKey } ?: true) }
    var keyMode by remember { mutableStateOf(KeyMode.EXISTING) }
    var password by remember { mutableStateOf((existing?.auth as? AuthMethod.Password)?.password.orEmpty()) }
    var privateKey by remember { mutableStateOf((existing?.auth as? AuthMethod.PrivateKey)?.pem.orEmpty()) }
    var passphrase by remember { mutableStateOf((existing?.auth as? AuthMethod.PrivateKey)?.passphrase.orEmpty()) }
    var passwordVisible by remember { mutableStateOf(false) }
    var protectWithPassphrase by remember { mutableStateOf(false) }
    var keyName by remember { mutableStateOf("flokk_${name.ifBlank { "key" }}") }
    var generated by remember { mutableStateOf<GeneratedSshKey?>(null) }

    var installPassword by remember { mutableStateOf("") }
    var installing by remember { mutableStateOf(false) }
    var installResult by remember { mutableStateOf<Result<Unit>?>(null) }

    var advancedOpen by remember { mutableStateOf(false) }
    var confirmDelete by remember { mutableStateOf(false) }
    var autoConnect by remember { mutableStateOf(existing?.autoConnect ?: false) }

    fun draft() = ConnectionProfile(
        id = existing?.id ?: UUID.randomUUID().toString(),
        name = name.trim(),
        host = host.trim(),
        port = port.toIntOrNull() ?: 22,
        username = username.trim(),
        auth = if (useKeyAuth) {
            AuthMethod.PrivateKey(privateKey, passphrase.takeIf { it.isNotBlank() })
        } else {
            AuthMethod.Password(password)
        },
        herdrSession = herdrSession.trim().takeIf { it.isNotBlank() },
        herdrBinary = herdrBinary.trim().takeIf { it.isNotBlank() } ?: "herdr",
        jumpHostId = jumpHostId,
        lastConnectedAt = existing?.lastConnectedAt,
        autoConnect = autoConnect,
    )

    val missing = listOfNotNull(
        "name".takeIf { name.isBlank() },
        "host".takeIf { host.isBlank() },
        "username".takeIf { username.isBlank() },
        (if (useKeyAuth) "key" else "password").takeIf { if (useKeyAuth) privateKey.isBlank() else password.isBlank() },
    )
    val unchanged = existing != null && draft() == existing
    val canSave = missing.isEmpty() && !unchanged
    val target = "${username.trim()}@${host.trim().ifBlank { "…" }}:$port"

    Column(modifier = Modifier.fillMaxSize().background(Flokk.background).imePadding()) {
        Row(
            modifier = Modifier.fillMaxWidth().height(50.dp).padding(horizontal = 16.dp),
            horizontalArrangement = Arrangement.spacedBy(12.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            HeaderIconButton(
                icon = Icons.AutoMirrored.Rounded.ArrowBack,
                contentDescription = "Back to connections",
                size = 40.dp,
                iconSize = 24.dp,
                tint = Flokk.text,
                shape = CircleShape,
                onClick = onCancel,
            )
            Column(modifier = Modifier.weight(1f)) {
                Text(text = if (existing == null) "Add connection" else "Edit connection", style = Flokk.screenTitle)
                if (host.isNotBlank() && username.isNotBlank()) {
                    Text(
                        text = target,
                        style = Flokk.monoSmall.copy(fontSize = 12.sp),
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis,
                    )
                }
            }
        }

        Column(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f)
                .verticalScroll(rememberScrollState())
                .padding(start = 20.dp, end = 20.dp, top = 4.dp, bottom = 20.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            FlokkTextField(value = name, onValueChange = { name = it }, label = "Name", placeholder = "e.g. home server")

            Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                FlokkTextField(
                    value = host,
                    onValueChange = { host = it },
                    label = "Host",
                    placeholder = "example.com or 10.0.0.5",
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Uri),
                    modifier = Modifier.weight(1f),
                )
                FlokkTextField(
                    value = port,
                    onValueChange = { port = it.filter(Char::isDigit) },
                    label = "Port",
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                    modifier = Modifier.width(88.dp),
                )
            }
            FlokkTextField(value = username, onValueChange = { username = it }, label = "Username", placeholder = "e.g. bart")

            LabelledField(label = "Sign in with") {
                SegmentedControl(
                    options = listOf(Segment("Key", Icons.Rounded.Key), Segment("Password", Icons.Rounded.Password)),
                    selectedIndex = if (useKeyAuth) 0 else 1,
                    onSelect = { useKeyAuth = it == 0 },
                )
            }

            if (useKeyAuth) {
                KeyAuthSection(
                    keyMode = keyMode,
                    onKeyMode = { keyMode = it },
                    privateKey = privateKey,
                    onPrivateKey = { privateKey = it },
                    passphrase = passphrase,
                    onPassphrase = { passphrase = it },
                    keyName = keyName,
                    onKeyName = { keyName = it },
                    protectWithPassphrase = protectWithPassphrase,
                    onProtectWithPassphrase = { protectWithPassphrase = it },
                    generated = generated,
                    onGenerated = { generated = it; installResult = null },
                    reusableKeys = otherProfiles.filter { it.auth is AuthMethod.PrivateKey },
                )
                generated?.let { g ->
                    InstallKeyCard(
                        target = "${username.trim()}@${host.trim()}",
                        password = installPassword,
                        onPassword = { installPassword = it },
                        installing = installing,
                        result = installResult,
                        canInstall = host.isNotBlank() && username.isNotBlank(),
                        onInstall = {
                            installing = true
                            installResult = null
                            scope.launch {
                                installResult = SshTransport.installPublicKey(
                                    host = host.trim(),
                                    port = port.toIntOrNull() ?: 22,
                                    username = username.trim(),
                                    password = installPassword,
                                    publicKeyLine = g.publicKeyLine,
                                    hostKeyVerifier = app.hostKeyVerifier,
                                ).map { }
                                installing = false
                                if (installResult?.isSuccess == true) installPassword = ""
                            }
                        },
                    )
                }
            } else {
                FlokkTextField(
                    value = password,
                    onValueChange = { password = it },
                    label = "Password",
                    visualTransformation = if (passwordVisible) VisualTransformation.None else PasswordVisualTransformation(),
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password, imeAction = ImeAction.Done),
                    trailing = {
                        HeaderIconButton(
                            icon = if (passwordVisible) Icons.Rounded.VisibilityOff else Icons.Rounded.Visibility,
                            contentDescription = if (passwordVisible) "Hide password" else "Show password",
                            size = 36.dp,
                            iconSize = 20.dp,
                            tint = Flokk.textFaint,
                            onClick = { passwordVisible = !passwordVisible },
                        )
                    },
                )
            }

            Column {
                ToggleRow(title = "Autoconnect on start", checked = autoConnect, onCheckedChange = { autoConnect = it })
                SettingsRow(
                    title = "Advanced",
                    subtitle = if (advancedOpen) null else "Jump host, herdr session, binary",
                    onClick = { advancedOpen = !advancedOpen },
                ) {
                    Icon(
                        if (advancedOpen) Icons.Rounded.ExpandLess else Icons.Rounded.ExpandMore,
                        contentDescription = if (advancedOpen) "Hide advanced" else "Show advanced",
                        tint = Flokk.textFaint,
                        modifier = Modifier.size(22.dp),
                    )
                }
            }

            if (advancedOpen) {
                Column(verticalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.padding(top = 0.dp)) {
                    Text("Jump host", style = Flokk.fieldLabel.copy(fontSize = 13.sp))
                    ChipGroup {
                        Chip(text = "None · direct", selected = jumpHostId == null, onClick = { jumpHostId = null })
                        otherProfiles.forEach { p ->
                            Chip(text = p.displayName, selected = jumpHostId == p.id, onClick = { jumpHostId = p.id })
                        }
                    }
                }
                FlokkTextField(
                    value = herdrSession,
                    onValueChange = { herdrSession = it },
                    label = "herdr session",
                    placeholder = "default",
                    helper = "Leave blank to keep HERDR_SESSION unset",
                )
                FlokkTextField(
                    value = herdrBinary,
                    onValueChange = { herdrBinary = it },
                    label = "Binary",
                    placeholder = "herdr",
                    helper = "If it's not on PATH, ~/.local/bin is tried too",
                    mono = true,
                )
            }

            if (existing != null) {
                Row(
                    modifier = Modifier
                        .padding(top = 8.dp)
                        .fillMaxWidth()
                        .height(44.dp)
                        .background(Flokk.card, RoundedCornerShape(10.dp))
                        .plainClickable { confirmDelete = true }
                        .padding(horizontal = 16.dp),
                    horizontalArrangement = Arrangement.spacedBy(12.dp),
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    Icon(Icons.Rounded.Delete, null, tint = Flokk.red, modifier = Modifier.size(20.dp))
                    Text("Delete connection", style = Flokk.bodyMedium.copy(color = Flokk.red))
                }
                if (confirmDelete) {
                    InlineConfirm(
                        title = "Delete connection?",
                        message = "“${existing.displayName}” will be removed from this device.",
                        confirmLabel = "Delete",
                        background = Flokk.card,
                        radius = 12.dp,
                        onConfirm = {
                            app.connectionManager.disconnect(existing.id)
                            app.profileStore.deleteProfile(existing.id)
                            confirmDelete = false
                            onSaved()
                        },
                        onCancel = { confirmDelete = false },
                    )
                }
            }
        }

        HorizontalDivider(thickness = 1.dp, color = Flokk.divider)
        Column(
            modifier = Modifier.fillMaxWidth().padding(start = 20.dp, end = 20.dp, top = 10.dp, bottom = 12.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            when {
                missing.isNotEmpty() -> IconLine(icon = Icons.Rounded.Info, text = "Add a ${joinWithAnd(missing)} to save")
                unchanged -> IconLine(icon = Icons.Rounded.Info, text = "No changes to save yet")
            }
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                OutlineButton(text = "Cancel", onClick = onCancel, modifier = Modifier.width(110.dp))
                PrimaryButton(
                    text = if (existing == null) "Save connection" else "Save changes",
                    enabled = canSave,
                    onClick = {
                        app.profileStore.saveProfile(draft())
                        onSaved()
                    },
                    modifier = Modifier.weight(1f),
                )
            }
        }
    }
}

/** "name, host, username and key" */
private fun joinWithAnd(items: List<String>): String =
    if (items.size <= 1) items.joinToString() else items.dropLast(1).joinToString(", ") + " and " + items.last()
